import { AUTORAL, alts, batch } from '../_helpers';

const fat = (n: number): number => (n <= 1 ? 1 : n * fat(n - 1));
const comb = (n: number, p: number) => fat(n) / (fat(p) * fat(n - p));

/** Números de 4 algarismos (1000 a 9999) com pelo menos dois algarismos iguais (busca exaustiva). */
function comRepeticao() {
  let n = 0;
  for (let x = 1000; x <= 9999; x++) if (new Set(String(x).split('')).size < 4) n++;
  return n;
}

