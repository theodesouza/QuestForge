const fat = (n: number): number => (n <= 1 ? 1 : n * fat(n - 1));

/** Números pares de 3 algarismos distintos (busca exaustiva). */
function paresDistintos() {
  let n = 0;
  for (let x = 100; x <= 999; x++) {
    const [a, b, c] = String(x).split('').map(Number);
    if (a !== b && b !== c && a !== c && c % 2 === 0) n++;
  }
  return n;
}

/** Números ímpares de 4 algarismos distintos formados com 1 a 6 (busca exaustiva). */
function imparesDe1a6() {
  let n = 0;
  for (let x = 1234; x <= 6543; x++) {
    const d = String(x).split('').map(Number);
    if (d.every((v) => v >= 1 && v <= 6) && new Set(d).size === 4 && d[3] % 2 === 1) n++;
  }
  return n;
}

