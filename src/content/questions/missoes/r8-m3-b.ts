/** Maior termo de três números em PA com soma 36 e produto 1.620 (busca direta). */
function maiorTermo() {
  for (let r = 0; r < 20; r++) {
    const a = [12 - r, 12, 12 + r];
    if (a[0] * a[1] * a[2] === 1620) return a[2];
  }
  return -1;
}

