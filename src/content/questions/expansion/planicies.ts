function mdc(a: number, b: number): number {
  while (b !== 0) [a, b] = [b, a % b];
  return a;
}

function mmc(a: number, b: number): number {
  return (a / mdc(a, b)) * b;
}

function menorQuadradoMultiplo(a: number, b: number): number {
  let lado = 1;
  while (lado ** 2 % a !== 0 || lado ** 2 % b !== 0) lado += 1;
  return lado ** 2;
}

